import { LevelProof, type LevelJson } from '@gg/schemas';
import { createSim, inputAtTick, winningRun, type FeedbackBinding } from '@gg/sdk';
import { afkWins, feedbackCoverage, levelPlan, recordEvents, simOptionsFor } from '@gg/template-core';
import { describe, expect, it } from 'vitest';
import { EXAMPLES, HIVE, LANTERN, ROOFTOP } from './examples.js';
import { generatorParams } from './levels.js';
import { BASE_MANIFESTS, freeformManifest } from './node.js';
import { idleWins, proveLevel, type ProveInputs } from './prove.js';

/** An example's levels as the levels stage lays them out, generated by the base grammar under the game's names. */
function levelsOf(ex: (typeof EXAMPLES)[number]) {
  const m = freeformManifest(ex.systems, ex.roster);
  const plan = levelPlan(m.levelGrammar.kind, { levels: ex.gdd.scope.levels, bosses: ex.gdd.scope.bosses, tier: ex.gdd.scopeTier });
  return plan.map((slot) => {
    const params = { seed: slot.index + 1, difficulty: slot.difficulty, ...(slot.boss ? { boss: 1 } : {}), ...generatorParams(ex.systems, ex.gdd.targets.levelTimeS) };
    const content = { ...(m.extraContent?.(params) ?? {}), ...(ex.objectives ? { objectives: ex.objectives } : {}), ...ex.content };
    return { level: { ...m.levelGrammar.generate(params), id: slot.id }, index: slot.index, content };
  });
}

const inputs = (ex: (typeof EXAMPLES)[number], content: Record<string, unknown>): ProveInputs => {
  const base = BASE_MANIFESTS[ex.systems.composition.base];
  return { file: ex.systems, roster: ex.roster, content, solver: base.bots[base.solverBot], budget: 20_000 };
};

describe('proveLevel', () => {
  for (const ex of EXAMPLES) {
    it(`${ex.id}: every level gets a winning run that replays`, () => {
      for (const { level, index, content } of levelsOf(ex)) {
        const r = proveLevel(level, index, inputs(ex, content));
        expect(r.proof, `${ex.id}/${level.id}: ${r.tried.join('; ')}`).not.toBeNull();
        expect(r.proof!.seed).toBe(index + 1);
        // A proof is kept while it still wins, and only then.
        expect(proveLevel(level, index, inputs(ex, content), r.proof!).tried).toEqual(['stored proof: wins']);
        // It plays like a game: standing still never wins, and every feedback event of the winning run is answered.
        const m = freeformManifest(ex.systems, ex.roster);
        const feedback = [...ex.gdd.feedbackEvents, ...(m.feedbackExtras ?? [])] as FeedbackBinding[];
        const make = () => createSim({ ...simOptionsFor(m, ex.systems, { content, feedback }), level, seed: index + 1 });
        expect(afkWins(make, Math.max(600, r.proof!.ticks * 2)), `${ex.id}/${level.id} afk`).toBe(false);
        const f = feedbackCoverage(recordEvents(make(), r.proof!.script, r.proof!.ticks), feedback);
        expect({ answered: f.answered, unbound: f.unbound }, `${ex.id}/${level.id} feedback`).toEqual({ answered: f.fired, unbound: [] });
      }
    });
  }

  it('tells a level that plays itself: a runner on flat ground wins standing still, a walker never does', () => {
    const rows = ['..........................', '..........................', '.S......................G.', '##########################'];
    const flat: LevelJson = { version: 1, id: 'l01', name: 'Flat', tileSize: 8, width: rows[0]!.length, height: rows.length, legend: { '.': 'air', '#': 'solid', S: 'air', G: 'goal' }, rows, entities: [], spawn: { x: 1, y: 2 }, goal: { x: 24, y: 2 } };
    const content = (ex: (typeof EXAMPLES)[number]) => ({ objectives: ex.objectives, ...ex.content });
    expect(idleWins(flat, 0, inputs(ROOFTOP, content(ROOFTOP)), 600)).toBe(true);
    expect(idleWins(flat, 0, inputs(LANTERN, content(LANTERN)), 600)).toBe(false);
    // A runner's own levels need it to jump.
    const { level, index, content: c } = levelsOf(ROOFTOP)[0]!;
    expect(idleWins(level, index, inputs(ROOFTOP, c), 1800)).toBe(false);
  });

  it("a player's run, as the game sends it on the win, replays to a win at the level's seed", () => {
    // A goal level and an arena: a winning run found here, played the way the realtime driver steps the sim.
    for (const ex of [LANTERN, HIVE]) {
      const { level, index, content } = levelsOf(ex)[0]!;
      const found = proveLevel(level, index, inputs(ex, content)).proof!;
      const m = freeformManifest(ex.systems, ex.roster);
      const sim = createSim({ ...simOptionsFor(m, ex.systems, { content }), level, seed: index + 1 });
      let sent: LevelProof | null = null;
      sim.events.on('level_complete', (ev) => {
        sent ??= winningRun(sim, ev.tick);
      });
      for (let t = 0; t < found.ticks + 60 && !sent; t++) sim.step(inputAtTick(found.script, t));
      expect(sent, ex.id).not.toBeNull();
      expect(LevelProof.parse(sent), ex.id).toMatchObject({ version: 1, level: level.id, seed: index + 1, ticks: found.ticks, by: 'human' });
      // What the verify job does with it: replayed on a fresh sim at its seed, it wins.
      expect(proveLevel(level, index, inputs(ex, content), sent!).tried, ex.id).toEqual(['stored proof: wins']);
    }
  });

  it('drops a stored proof that no longer wins and finds another', () => {
    const { level, index, content } = levelsOf(HIVE)[0]!;
    const stale: LevelProof = { version: 1, level: level.id, seed: index + 1, ticks: 60, by: 'human', script: [{ from: 0, to: 60, input: { right: true } }] };
    const r = proveLevel(level, index, inputs(HIVE, content), stale);
    expect(r.tried[0]).toBe('stored proof: no longer wins');
    expect(r.proof?.by).not.toBe('human');
  });
});
